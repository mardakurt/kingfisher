#!/usr/bin/env node
/**
 * What a claim search costs, before and after the claim index.
 *
 * Phase 18 left this as its first known limitation: 2,312 ms on 11.3 million
 * positions, with the direction named and the work out of scope. This measures
 * the fix on the same scale — a real collection built from the Lichess
 * broadcast archives through the application's own import path.
 *
 * Three states are timed, not two, because two would hide which half of the
 * change did the work:
 *
 *   1. **Phase 18.** The query exactly as it was: `LIKE` over every claim set,
 *      joined to `games`, ordered by that table's rating and year. Run as raw
 *      SQL against a read-only handle so that nothing this phase added can be
 *      used by accident.
 *   2. **Sorting on the position row.** The same matching, ordered by
 *      `positions.rating_key` and `year_key` instead — the columns that hold
 *      the game's own rating and year, so the join is needed for the rows
 *      returned rather than for every row matched.
 *   3. **The claim index.** `claim_set_members` instead of the `LIKE`, and an
 *      ordered walk of the rank index that stops at thirty.
 *
 * And it is not one query. A single claim can be made to say anything: a rare
 * one is fast under every plan and a common one is slow under all but the
 * last. So this samples the whole selectivity spectrum, runs all three
 * orderings, and reports the distribution.
 *
 *   node scripts/bench-claim-search.mjs --db .real-scale/real.sqlite
 *   node scripts/bench-claim-search.mjs --db … --skip-build   # re-time only
 */

import { DatabaseSync } from 'node:sqlite';
import { statSync } from 'node:fs';
import path from 'node:path';
import { performance } from 'node:perf_hooks';
import { argv, exit } from 'node:process';
import { fileURLToPath } from 'node:url';

import { GameDatabase } from '../companion/src/database.mjs';
import { buildClaimIndex, claimIndexReady } from '../companion/src/position-schema.mjs';

const ROOT = fileURLToPath(new URL('..', import.meta.url));

function parseArgs(list) {
  const args = {
    db: path.join(ROOT, '.real-scale', 'real.sqlite'),
    /*
      Modest on purpose. At this scale each "before" query reads millions of
      rows out of a five-gigabyte file, so forty runs of the same slow query
      would take an afternoon to say what four already say. What matters is
      the spread across the selectivity spectrum, not the sample size at any
      one point on it.
    */
    warm: 3,
    claims: 12,
    skipBuild: false,
  };
  for (let i = 0; i < list.length; i += 1) {
    if (list[i] === '--db') args.db = path.resolve(list[++i]);
    else if (list[i] === '--warm') args.warm = Number(list[++i]);
    else if (list[i] === '--claims') args.claims = Number(list[++i]);
    else if (list[i] === '--skip-build') args.skipBuild = true;
  }
  return args;
}

const n = (value) => Number(value).toLocaleString('en-GB');
const mb = (bytes) => `${(bytes / 1e6).toFixed(0)} MB`;

/** Nearest-rank percentile, the way every other benchmark here does it. */
const percentile = (sorted, q) =>
  sorted[Math.min(sorted.length - 1, Math.ceil(q * sorted.length) - 1)];

function time(run, warm) {
  run();
  const samples = [];
  for (let i = 0; i < warm; i += 1) {
    const started = performance.now();
    run();
    samples.push(performance.now() - started);
  }
  samples.sort((a, b) => a - b);
  return samples;
}

const summarise = (all) => {
  const sorted = [...all].sort((a, b) => a - b);
  return {
    median: percentile(sorted, 0.5),
    p95: percentile(sorted, 0.95),
    worst: sorted[sorted.length - 1],
    n: sorted.length,
  };
};

const row = (label, stats) =>
  `${label.padEnd(34)} median ${stats.median.toFixed(1).padStart(9)}  ` +
  `p95 ${stats.p95.toFixed(1).padStart(9)}  worst ${stats.worst.toFixed(1).padStart(9)}  ` +
  `(${stats.n} queries)`;

/**
 * Claims spread across the whole range of how often they occur.
 *
 * Taken from the collection itself rather than written down: the vocabulary is
 * generated by `structureClaims` and the material profiles are open-ended, so
 * a hand-written list would be a guess about the data.
 */
function sampleClaims(db, count) {
  const sets = db.prepare('SELECT value FROM structure_claim_sets').all();
  const frequency = new Map();
  for (const entry of sets) {
    let list;
    try {
      list = JSON.parse(entry.value);
    } catch {
      continue;
    }
    for (const claim of Array.isArray(list) ? list : []) {
      if (typeof claim === 'string') frequency.set(claim, (frequency.get(claim) ?? 0) + 1);
    }
  }
  const ordered = [...frequency.entries()].sort((a, b) => b[1] - a[1]);
  // Log-spaced, so the sample is not all common claims or all singletons.
  const picked = [];
  for (let i = 0; i < count; i += 1) {
    const at = Math.min(
      ordered.length - 1,
      Math.round((ordered.length - 1) * (i / Math.max(1, count - 1)) ** 2),
    );
    const entry = ordered[at];
    if (entry && !picked.some((p) => p.claim === entry[0]))
      picked.push({ claim: entry[0], sets: entry[1] });
  }
  return { picked, totalSets: sets.length };
}

async function main() {
  const args = parseArgs(argv.slice(2));
  console.log('Kingfisher claim-search benchmark');
  console.log(`node ${process.version} · ${process.platform}-${process.arch}`);
  console.log(`database: ${args.db}\n`);

  const before = statSync(args.db).size;
  const raw = new DatabaseSync(args.db, { readOnly: true });
  const positions = raw.prepare('SELECT COUNT(*) AS c FROM positions').get().c;
  const games = raw.prepare('SELECT COUNT(*) AS c FROM games').get().c;
  const { picked, totalSets } = sampleClaims(raw, args.claims);
  console.log(
    `${n(games)} games · ${n(positions)} positions · ${n(totalSets)} claim sets · ${mb(before)}`,
  );
  console.log(
    `${picked.length} claims sampled, from ${n(picked[0].sets)} claim sets down to ${n(picked.at(-1).sets)}\n`,
  );

  /*
    State 1 — Phase 18, verbatim. Built here rather than called, so that the
    "before" number cannot accidentally benefit from anything added since.
  */
  const phase18 = raw.prepare(
    `SELECT g.*, p.position_key, p.game_id, p.ply
       FROM positions p
       LEFT JOIN structure_claim_sets cs ON cs.id = p.structure_claims_id
       JOIN games g ON g.id = p.game_id
      WHERE p.structure_claims_id IN (SELECT id FROM structure_claim_sets WHERE value LIKE ?)
      ORDER BY g.max_rating DESC, g.year DESC
      LIMIT 30`,
  );
  const onRow = raw.prepare(
    `SELECT g.*, p.position_key, p.game_id, p.ply
       FROM positions p
       LEFT JOIN structure_claim_sets cs ON cs.id = p.structure_claims_id
       JOIN games g ON g.id = p.game_id
      WHERE p.structure_claims_id IN (SELECT id FROM structure_claim_sets WHERE value LIKE ?)
      ORDER BY p.rating_key DESC, p.year_key DESC
      LIMIT 30`,
  );

  /*
    One run per claim, not `warm` runs, and the reason is worth stating rather
    than hiding in a flag.

    A claim search under the old plan is latency-bound, not throughput-bound:
    the common claims match millions of position rows and each one is a random
    read into `games`. On this collection the commonest claim takes minutes,
    so repeating it four times measures the page cache rather than the query.
    One run each across twelve claims is a spread; forty runs of one claim is
    what Phase 18 reported, and it is measured separately below so that the two
    numbers can actually be compared.
  */
  console.log('--- before: the claim index does not exist -----------------------');
  const oldTimes = [];
  const rowTimes = [];
  for (const entry of picked) {
    const like = `%${JSON.stringify(entry.claim)}%`;
    let started = performance.now();
    phase18.all(like);
    const oldMs = performance.now() - started;
    started = performance.now();
    onRow.all(like);
    const rowMs = performance.now() - started;
    oldTimes.push(oldMs);
    rowTimes.push(rowMs);
    console.log(
      `  ${entry.claim.padEnd(28)} ${n(entry.sets).padStart(9)} sets  ` +
        `phase18 ${oldMs.toFixed(0).padStart(8)} ms   on-row ${rowMs.toFixed(0).padStart(8)} ms`,
    );
  }
  console.log('');
  console.log(row('Phase 18, sorted via games', summarise(oldTimes)));
  console.log(row('sorted on the position row', summarise(rowTimes)));
  raw.close();

  if (args.skipBuild) return { before, oldTimes, rowTimes };

  /*
    Opening through `GameDatabase` is what a companion does, and it is what
    creates the rank indexes. Timed, because it is a cost a user pays once and
    a report that leaves it out is not describing what happened.
  */
  console.log('\n--- building ------------------------------------------------------');
  let started = performance.now();
  const database = new GameDatabase(args.db);
  const openMs = performance.now() - started;
  console.log(
    `opening the collection                              ${(openMs / 1000).toFixed(1)} s`,
  );

  const handle = database.handleForTest();
  started = performance.now();
  const built = buildClaimIndex(handle, {
    onProgress: ({ indexed, total }) => {
      if (indexed % 200_000 === 0) {
        process.stdout.write(`  ${n(indexed)} / ${n(total)} claim sets\r`);
      }
    },
  });
  const buildMs = performance.now() - started;
  console.log(
    `building the claim index                            ${(buildMs / 1000).toFixed(1)} s  ` +
      `(${n(built.total)} claim sets, done=${built.done})`,
  );
  if (!claimIndexReady(handle)) throw new Error('The build finished and the index is not ready.');
  const claims = handle.prepare('SELECT COUNT(*) AS c FROM claims').get().c;
  const members = handle.prepare('SELECT COUNT(*) AS c FROM claim_set_members').get().c;
  console.log(`distinct claims ${n(claims)} · claim/set pairs ${n(members)}`);

  console.log('\n--- after: through the product’s own search ------------------------');
  const query = (claim, sort) => ({
    mode: 'claims',
    claims: [claim],
    positionKey: '',
    pawnSkeleton: '',
    structureSignature: '',
    sort,
    limit: 30,
  });
  const bySort = { closest: [], rating: [], recent: [] };
  const rowsReturned = [];
  for (const entry of picked) {
    for (const sort of ['closest', 'rating', 'recent']) {
      const run = () => database.searchStructures(query(entry.claim, sort));
      rowsReturned.push(run().length);
      bySort[sort].push(...time(run, args.warm));
    }
  }
  for (const sort of ['closest', 'rating', 'recent']) {
    console.log(row(`claim search, sort=${sort}`, summarise(bySort[sort])));
  }
  const everything = [...bySort.closest, ...bySort.rating, ...bySort.recent];
  console.log(row('all sorts together', summarise(everything)));

  /*
    The fallback is deliberately not re-timed here.

    It is the query measured above, and it only ever runs on a collection with
    no claim index — which is a collection with no rank indexes either, because
    those are built by the job that builds the claim index. Timing it *now*,
    with the rank indexes present, would measure a configuration that cannot
    occur: the planner reaches for a rank scan it then has to sort anyway, and
    on this collection the commonest claim goes from 30.6 s to 78.5 s. That is
    the reason they are not built on open.
  */

  const after = statSync(args.db).size;
  console.log(
    `\nsize ${mb(before)} → ${mb(after)}  (+${mb(after - before)}, ` +
      `${(((after - before) / before) * 100).toFixed(1)}%)`,
  );

  const oldStats = summarise(oldTimes);
  const newStats = summarise(everything);
  console.log(
    `\nmedian ${oldStats.median.toFixed(1)} ms → ${newStats.median.toFixed(1)} ms  ` +
      `(${(oldStats.median / newStats.median).toFixed(0)}x)   ` +
      `worst ${oldStats.worst.toFixed(1)} ms → ${newStats.worst.toFixed(1)} ms`,
  );
  database.close();
  return { before, after };
}

main().catch((error) => {
  console.error(error);
  exit(1);
});
