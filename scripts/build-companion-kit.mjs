#!/usr/bin/env node
/**
 * Bundle the application's import path for the companion (Phase 85):
 * `src/companion-kit/import-kit.ts` and everything it imports, as one ES
 * module at `companion/generated/import-kit.mjs`. Built, not committed; the
 * companion builds it on first use in a checkout (`import-jobs.mjs`), the
 * desktop build stages it with the companion, and
 * `companion/src/import-kit.test.mjs` builds it and imports a game through it.
 */

import { mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { build } from 'rolldown';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
export const KIT_FILE = path.join(ROOT, 'companion', 'generated', 'import-kit.mjs');

export async function buildCompanionKit(outFile = KIT_FILE) {
  mkdirSync(path.dirname(outFile), { recursive: true });
  await build({
    input: path.join(ROOT, 'src', 'companion-kit', 'import-kit.ts'),
    platform: 'node',
    resolve: { alias: { '@': path.join(ROOT, 'src') } },
    logLevel: 'warn',
    output: {
      file: outFile,
      format: 'esm',
      codeSplitting: false,
      banner:
        '// GENERATED by scripts/build-companion-kit.mjs from src/companion-kit/import-kit.ts. Do not edit.',
    },
  });
  return outFile;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const file = await buildCompanionKit(process.argv[2] ?? KIT_FILE);
  console.log(`wrote ${path.relative(ROOT, file)}`);
}
