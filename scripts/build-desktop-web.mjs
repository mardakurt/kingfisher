#!/usr/bin/env node
/**
 * Build the web application the way the desktop shell serves it.
 *
 * The desktop shell runs the same Next application the browser does — that is
 * the point of it, and the reason there is no second renderer, no second
 * router and no second copy of the chess code. What it cannot do is assume a
 * `node_modules` tree next to the server, so this produces Next's standalone
 * output and assembles the three pieces Next deliberately leaves to the
 * packager:
 *
 *   .next/standalone/          the server, and only the modules it reached
 *   .next/static/          →   .next/standalone/.next/static
 *   public/                →   .next/standalone/public
 *
 * The result lands in `desktop/app/`, which is what `electron-builder` packs.
 *
 * Cross-origin isolation is switched on for this build and not for the web
 * one. In a browser it is a deployment decision with a real cost — COEP
 * constrains what the page may embed — and Kingfisher leaves it to whoever
 * deploys. In the desktop shell there is nothing third-party to embed and the
 * shell owns the server, so the multi-threaded engine simply works.
 *
 *   node scripts/build-desktop-web.mjs
 */

import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const STANDALONE = path.join(ROOT, '.next', 'standalone');
const OUT = path.join(ROOT, 'desktop', 'web');

const size = (dir) => {
  let total = 0;
  const walk = (p) => {
    const stat = statSync(p);
    if (!stat.isDirectory()) {
      total += stat.size;
      return;
    }
    for (const entry of readdirSync(p)) walk(path.join(p, entry));
  };
  walk(dir);
  return total;
};

console.log('Building the desktop web bundle');
console.log(`node ${process.version} · ${process.platform}-${process.arch}\n`);

execFileSync('npx', ['next', 'build'], {
  cwd: ROOT,
  stdio: 'inherit',
  env: {
    ...process.env,
    KINGFISHER_DESKTOP_BUILD: '1',
    KINGFISHER_CROSS_ORIGIN_ISOLATION: '1',
  },
});

if (!existsSync(path.join(STANDALONE, 'server.js'))) {
  console.error(
    '\nNext produced no standalone server. That means `output: "standalone"` did not apply — ' +
      'check that next.config.ts still reads KINGFISHER_DESKTOP_BUILD.',
  );
  process.exit(1);
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(path.dirname(OUT), { recursive: true });
cpSync(STANDALONE, OUT, { recursive: true });
cpSync(path.join(ROOT, '.next', 'static'), path.join(OUT, '.next', 'static'), { recursive: true });
/*
  `public/`, minus the developer artefacts, and only once what must be there is.

  A straight recursive copy put every generated file a developer happened to
  have lying about into the signed application bundle — on the machine that
  built Phase 20's first candidate, 2.9 MB of benchmark PGNs that no code reads
  and CI would not have had. What is inside an application handed to strangers
  should be a property of the repository, not of whose laptop built it.

  The first attempt at this asked git what it was ignoring and left all of it
  out, which was wrong in a way worth recording: `public/engine/` is ignored
  too, and it holds the Stockfish WebAssembly that `npm run engine:install`
  fetches. Excluding it produced a perfectly valid 67 MB application with no
  engine in it, and the build reported success. **Ignored by git and not needed
  at runtime are different claims**, and only the second one matters here.

  So the two are stated separately and neither is inferred:

    EXCLUDED   developer artefacts, named, with a reason each.
    REQUIRED   runtime assets that must exist, checked after the copy, so a
               missing one fails the build instead of shipping quietly.
*/
const EXCLUDED = [
  // Generated by the benchmark scripts, read by nothing, git-ignored.
  { at: 'bench', because: 'benchmark fixtures; `npm run bench:*` regenerates them' },
];

const REQUIRED = [
  { at: 'engine/stockfish', because: 'the browser engine; run `npm run engine:install`' },
  { at: 'engine/manifest.json', because: 'the engine manifest; run `npm run engine:install`' },
];

const excludedRoots = EXCLUDED.map((entry) => path.join(ROOT, 'public', entry.at));
let skipped = 0;
cpSync(path.join(ROOT, 'public'), path.join(OUT, 'public'), {
  recursive: true,
  filter: (source) => {
    if (!excludedRoots.some((root) => source === root || source.startsWith(`${root}${path.sep}`))) {
      return true;
    }
    if (statSync(source).isFile()) skipped += 1;
    return false;
  },
});
if (skipped > 0) {
  console.log(
    `  (left out ${skipped} developer artefact(s): ${EXCLUDED.map((e) => e.at).join(', ')})`,
  );
}

/*
  The image optimiser's native dependency, which nothing in Kingfisher reaches.

  `next/image` is rendered nowhere — the pieces are a few hundred bytes of SVG
  drawn with a plain `<img>` — and `next.config.ts` declares
  `images.unoptimized` for this build, so the optimiser route is off. Next's
  standalone trace includes `sharp` and its 27 MB of libvips binaries anyway,
  because the tracer follows what the compiled server *could* import rather
  than what this configuration will.

  Declaring `unoptimized` alone did not remove them — measured, not assumed:
  the bundle was still 379 MB with it set. So they are pruned here, and the
  claim that this is safe was tested rather than reasoned about. With both
  directories deleted the standalone server starts and answers `/analysis`,
  `/openings`, `/players`, `/databases`, `/studies`, `/repertoire`, `/review`,
  `/training` and `/endgame` with HTTP 200, and serves the 7.3 MB Stockfish
  WebAssembly and the starter pack manifest.
*/
const UNREACHABLE = ['@img', 'sharp'];
let pruned = 0;
for (const name of UNREACHABLE) {
  const at = path.join(OUT, 'node_modules', name);
  if (!existsSync(at)) continue;
  pruned += size(at);
  rmSync(at, { recursive: true, force: true });
}
if (pruned > 0) {
  console.log(
    `  (pruned ${(pruned / 1e6).toFixed(1)} MB: ${UNREACHABLE.join(', ')} — no next/image)`,
  );
}

const absent = REQUIRED.filter((entry) => !existsSync(path.join(OUT, 'public', entry.at)));
if (absent.length > 0) {
  console.error('\nThe bundle is missing assets the application needs at runtime:\n');
  for (const entry of absent) console.error(`  public/${entry.at} — ${entry.because}`);
  console.error('\nRefusing to assemble an application that would launch without them.');
  process.exit(1);
}

/*
  Take the build machine's own paths out of what gets signed and shipped.

  `npm run tablebase:install` records the absolute path of the helper it just
  compiled, and that record lives under `public/`, so a bundle built here
  shipped `/Users/<whoever built it>/…/kingfisher-tbprobe` to everybody given a
  copy. Two problems in one line: it discloses the builder's account name and
  directory layout, and it names a file that cannot exist on the machine
  reading it.

  The rest of the record is provenance worth keeping — the upstream repository,
  the commit, the licence and the source digests describe the helper wherever
  it came from — so the path is dropped rather than the file. The companion
  resolves the binary on the machine it is actually running on; see
  `tablebaseBinary()`.
*/
const buildRecord = path.join(OUT, 'public', 'engine', 'tablebase.json');
if (existsSync(buildRecord)) {
  const record = JSON.parse(readFileSync(buildRecord, 'utf8'));
  if (record.helper) {
    delete record.helper;
    record.helperPathRemoved =
      'Removed at packaging: it named the build machine. The companion finds the helper itself.';
    writeFileSync(buildRecord, `${JSON.stringify(record, null, 2)}\n`);
    console.log(
      '  (removed the build machine\u2019s helper path from public/engine/tablebase.json)',
    );
  }
}

console.log(`\nAssembled ${path.relative(ROOT, OUT)}`);
for (const part of ['server.js', '.next/static', 'public']) {
  const at = path.join(OUT, part);
  const mark = existsSync(at) ? '✓' : '✗';
  const bytes = existsSync(at) ? ` ${(size(at) / 1e6).toFixed(1)} MB` : '';
  console.log(`  ${mark} ${part}${bytes}`);
}
console.log(`  total ${(size(OUT) / 1e6).toFixed(1)} MB`);
