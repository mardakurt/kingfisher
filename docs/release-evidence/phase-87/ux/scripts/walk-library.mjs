/* eslint-disable no-console -- measurement scripts report on stdout */
import { chromium } from '@playwright/test';
import { readFileSync } from 'node:fs';
const out = process.argv[2];
const browser = await chromium.launch({ channel: 'chrome' });
const page = await (await browser.newContext({ viewport:{width:1440,height:860} })).newPage();
await page.goto('http://localhost:3210/games');
await page.locator('html[data-kingfisher-ready="true"]').waitFor();
await page.waitForFunction(() => Boolean(globalThis.__kingfisher));
const pgn = readFileSync('public/bench/bench-1k.pgn','utf8').split('\n\n[Event').slice(0,200).join('\n\n[Event');
await page.evaluate(async (t) => { const a = globalThis.__kingfisher; await a.importGames(t, a.games); }, pgn);
await page.reload(); await page.locator('html[data-kingfisher-ready="true"]').waitFor(); await page.waitForTimeout(1500);
await page.getByPlaceholder(/Search players/).fill('Carlsen');
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/lib-search.png` });
await page.locator('tbody tr').first().click();
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/lib-preview.png` });
await page.getByRole('button', { name: 'Filters' }).click().catch(()=>{});
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/lib-filters.png` });
await page.keyboard.press('Escape');
await page.locator('tbody tr').first().dblclick();
await page.waitForTimeout(2500);
console.log('after open', page.url());
await page.screenshot({ path: `${out}/lib-opened.png` });
await page.goBack(); await page.waitForTimeout(2000);
console.log('after back', page.url(), await page.getByPlaceholder(/Search players/).inputValue().catch(()=>'?'));
await page.screenshot({ path: `${out}/lib-back.png` });
await browser.close();
